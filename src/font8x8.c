static uint8_t packed[128][8];
static int ready;

static void init(void)
{
    for (int c = 0; c < 95; c++)
        for (int r = 0; r < 8; r++) {
            uint8_t b = 0;
            for (int x = 0; x < 8; x++)
                if (art[c][r][x] == '#')
                    b |= (uint8_t)(0x80 >> x);
            packed[0x20 + c][r] = b;
        }
    ready = 1;
}

const uint8_t *font8x8_glyph(int ch)
{
    if (!ready)
        init();
    return packed[ch & 0x7F]; /* control characters (00h-1Fh) and 7Fh are blank */
}
